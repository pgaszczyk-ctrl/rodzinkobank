// Turns assets/scene/scena.json into src/scenedata.js and adds a content hash to
// every file URL, so browsers always load the current artwork.  npm run build:scene
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';

const root = new URL('../assets/scene/', import.meta.url);
const scene = JSON.parse(readFileSync(new URL('scena.json', root), 'utf8'));
const hash = (f) => createHash('sha1').update(readFileSync(new URL(f, root))).digest('hex').slice(0, 8);
for (const a of Object.values(scene.assets)) {
  if (!a.raster) a.url = `assets/scene/${a.file}?v=${hash(a.file)}`;
  else {
    const webp = a.raster.replace(/\.png$/, '.webp');
    const r = existsSync(new URL(webp, root)) ? webp : a.raster;
    a.url = `assets/scene/${r}?v=${hash(r)}`;   // miners: the frames themselves (alpha WebP)
  }
}
writeFileSync(new URL('../src/scenedata.js', import.meta.url),
  `// GENERATED by tools/build-scene.mjs from assets/scene/scena.json – do not edit by hand.\nexport const SCENE = ${JSON.stringify(scene)};\n`);
console.log('scenedata.js:', Object.keys(scene.assets).length, 'assets,', scene.layers.length, 'layers');
