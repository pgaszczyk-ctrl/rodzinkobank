// Turns the illustrator's SVG files (assets/art/*.svg) into src/artkit.js.
// Run after changing any illustration:  npm run build:art
//
// * Every id becomes a class "gk-<id>" so one drawing can be placed many times
//   and its moving parts animated from CSS (see assets/app.css).
// * Ids that are referenced (clip paths) keep a placeholder prefix that
//   artkit.js replaces with a unique one for each copy.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const dir = new URL('../assets/art/', import.meta.url);
const out = {};
for (const f of readdirSync(dir).filter((n) => n.endsWith('.svg') && !n.startsWith('_')).sort()) {
  const src = readFileSync(new URL(f, dir), 'utf8');
  const vb = src.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/);
  let inner = src.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  if (/<script|on\w+=|href="(?!#)/i.test(inner)) throw new Error(`${f}: unexpected script or external reference`);
  const referenced = new Set([...inner.matchAll(/url\(#([\w-]+)\)|href="#([\w-]+)"/g)].map((m) => m[1] || m[2]));
  inner = inner.replace(/\sid="([\w-]+)"/g, (_, id) => (referenced.has(id) ? ` id="__P__${id}"` : ` class="gk-${id}"`));
  inner = inner.replace(/url\(#([\w-]+)\)/g, 'url(#__P__$1)').replace(/href="#([\w-]+)"/g, 'href="#__P__$1"');
  inner = inner.replace(/\s(transform|stroke-width)=""/g, '').replace(/\s+/g, ' ').trim();
  out[f.replace(/\.svg$/, '')] = { w: Number(vb[1]), h: Number(vb[2]), svg: inner };
}

const body = `// GENERATED by tools/build-art.mjs from assets/art/*.svg – do not edit by hand.
// Illustrations: Groszaki SVG v2. Moving parts carry "gk-*" classes.

export const ART = ${JSON.stringify(out, null, 1)};

let uid = 0;

/**
 * Markup of one illustration placed at (x, y) and scaled.
 * opts.flip mirrors it horizontally; opts.recolor maps colours (e.g. shirt);
 * opts.cls adds a class on the wrapper ("art-<name>" is always added).
 */
export function art(name, { x = 0, y = 0, scale = 1, sx = null, sy = null, flip = false, recolor = null, cls = '', attrs = '' } = {}) {
  const a = ART[name];
  if (!a) throw new Error('unknown art ' + name);
  let svg = a.svg;
  if (svg.includes('__P__')) { const p = 'gk' + (++uid) + '-'; svg = svg.replace(/__P__/g, p); }
  if (recolor) for (const [from, to] of Object.entries(recolor)) svg = svg.split(from).join(to);
  const kx = sx ?? scale, ky = sy ?? scale;
  const tf = flip ? \`translate(\${x + a.w * kx} \${y}) scale(\${-kx} \${ky})\` : \`translate(\${x} \${y}) scale(\${kx} \${ky})\`;
  return \`<g class="art-\${name} \${cls}" transform="\${tf}" \${attrs}>\${svg}</g>\`;
}

/** A standalone <svg> element (for icons and the balance mascot). */
export function artSvg(name, { cls = '', recolor = null, label = '', viewBox = null } = {}) {
  const a = ART[name];
  return \`<svg viewBox="\${viewBox || \`0 0 \${a.w} \${a.h}\`}" class="\${cls}" \${label ? \`role="img" aria-label="\${label}"\` : 'aria-hidden="true"'}>\${art(name, { recolor })}</svg>\`;
}
`;
writeFileSync(new URL('../src/artkit.js', import.meta.url), body);
console.log('artkit.js:', Object.keys(out).length, 'illustrations');
