// Cache busting without a bundler: writes an import map into index.html that
// maps every module in src/ to "<file>?v=<content hash>", and stamps the CSS
// links the same way. Browsers (and GitHub Pages' 10-minute cache) then always
// load the current files after a change.  Run:  npm run stamp
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const root = new URL('../', import.meta.url);
const hash = (p) => createHash('sha1').update(readFileSync(new URL(p, root))).digest('hex').slice(0, 8);
const files = [];
const walk = (dir) => {
  for (const e of readdirSync(new URL(dir, root), { withFileTypes: true })) {
    if (e.isDirectory()) walk(`${dir}${e.name}/`);
    else if (e.name.endsWith('.js')) files.push(`${dir}${e.name}`);
  }
};
walk('src/');
const imports = Object.fromEntries(files.sort().map((f) => [`./${f}`, `./${f}?v=${hash(f)}`]));
const map = `<!-- import-map:start (generated by tools/stamp.mjs) -->\n<script type="importmap">${JSON.stringify({ imports })}</script>\n<!-- import-map:end -->`;

let html = readFileSync(new URL('index.html', root), 'utf8');
if (html.includes('<!-- import-map:start')) html = html.replace(/<!-- import-map:start[\s\S]*?<!-- import-map:end -->/, map);
else html = html.replace('<link rel="stylesheet" href="assets/tailwind.css', `${map}\n<link rel="stylesheet" href="assets/tailwind.css`);
for (const css of ['assets/tailwind.css', 'assets/app.css']) {
  html = html.replace(new RegExp(`href="${css.replace('.', '\\.')}(\\?v=[0-9a-f]+)?"`), `href="${css}?v=${hash(css)}"`);
}
html = html.replace(/<script type="module" src="src\/app\.js(\?v=[0-9a-f]+)?"><\/script>/, `<script type="module" src="./src/app.js?v=${hash('src/app.js')}"></script>`);
writeFileSync(new URL('index.html', root), html);
console.log('stamped', files.length, 'modules');
